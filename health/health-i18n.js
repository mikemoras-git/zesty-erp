/**
 * Care Log — language layer (English / Ελληνικά)
 * Load BEFORE health-base.js on every page.
 *
 * Static markup is translated through `data-i18n` attributes; dynamic strings
 * go through t('key', {vars}). Domain labels (event types, metrics, lab tests)
 * carry their Greek inline in health-base.js and resolve through L().
 *
 * To correct a translation, edit the `el` side of the pair below — nothing else
 * needs to change.
 */

const LANG_KEY = 'carelog_lang';

function getLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'en' || saved === 'el') return saved;
  } catch {}
  /* First run: follow the browser, since the patient is the likelier reader. */
  return (navigator.language || '').toLowerCase().startsWith('el') ? 'el' : 'en';
}

function setLang(lang) {
  try { localStorage.setItem(LANG_KEY, lang === 'el' ? 'el' : 'en'); } catch {}
  /* A reload is the honest way to re-render every chart, table and modal. */
  location.reload();
}

/** Locale tag for date formatting. */
function localeTag() { return getLang() === 'el' ? 'el-GR' : 'en-GB'; }

/** Pick the right side of a { label, el } pair from the domain tables. */
function L(def) {
  if (!def) return '';
  return getLang() === 'el' && def.el ? def.el : (def.label || '');
}

/** Translate a key, with optional {placeholder} interpolation. */
function t(key, vars) {
  const dict = STRINGS[getLang()] || STRINGS.en;
  let s = dict[key];
  if (s === undefined) s = STRINGS.en[key];
  if (s === undefined) s = key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

/** Apply translations to the static markup of the current page. */
function applyI18n(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
  scope.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.getAttribute('data-i18n-html')); });
  scope.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.getAttribute('data-i18n-ph')); });
  scope.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.getAttribute('data-i18n-title')); });
  if (!root) {
    document.documentElement.lang = getLang();
    const titleKey = document.body && document.body.getAttribute('data-i18n-doctitle');
    if (titleKey) document.title = t(titleKey);
  }
}

